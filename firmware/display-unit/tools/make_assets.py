#!/usr/bin/env python3
"""Builds the LVGL image assets for the 1024x600 display unit.

* Vector art (characters, alert icons) is cut out of the design prototype and rasterised
  with headless Chrome (transparent background).
* Photos (car, crest) come from design/assets.
* Everything is written to main/assets/img_*.c.

Render rule: wherever the picture always sits on a flat colour (screen background, the level
card) it is flattened onto that colour and stored as opaque RGB565.
Opaque images are drawn by copying, which is ~4x cheaper than alpha blending on the ESP32-S3,
and they take 2 bytes per pixel instead of 3. Only the small characters on the dial keep an
alpha channel (they cross the dial track). The mirrored copy used in reverse gear is not stored:
the firmware builds it in RAM on demand (ui_char_flipped).

usage: python3 tools/make_assets.py [DESIGN_DIR]     (needs Pillow and Google Chrome)
"""
import os
import re
import subprocess
import sys
import tempfile

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DESIGN = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.join(ROOT, "design")
OUT = os.path.join(ROOT, "main", "assets")
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
K = 1.25  # 800x480 design -> 1024x600 panel

BG = (10, 10, 12)        # screen background (C_BG in ui_priv.h)
CARD = (20, 22, 26)      # level card (#14161a)

html_src = open(os.path.join(DESIGN, "display-unit.html"), encoding="utf-8").read()


def svg_group(name):
    m = re.search(r'<g id="%s">\n(.*?)\n</g>' % name, html_src, re.S)
    if not m:
        raise SystemExit("group %s not found in design" % name)
    return m.group(1)


def render(svg_body, w, h, tmp, name):
    """Render an SVG snippet at w x h px with a transparent background."""
    page = os.path.join(tmp, name + ".html")
    png = os.path.join(tmp, name + ".png")
    with open(page, "w", encoding="utf-8") as f:
        f.write('<!doctype html><html><body style="margin:0;background:transparent;overflow:hidden">'
                '<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" style="display:block">%s</svg>'
                "</body></html>" % (w, h, svg_body))
    subprocess.run([CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars",
                    "--force-device-scale-factor=1", "--default-background-color=00000000",
                    "--window-size=%d,%d" % (w, h), "--screenshot=" + png, "file://" + page],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return Image.open(png).convert("RGBA").crop((0, 0, w, h))


def flat(img, rgb):
    """Flatten onto a solid colour (result is fully opaque)."""
    bg = Image.new("RGBA", img.size, rgb + (255,))
    bg.alpha_composite(img.convert("RGBA"))
    return bg


def to_c(img, name, fmt="RGB565A8"):
    img = img.convert("RGBA")
    if os.environ.get("PREVIEW_DIR"):
        img.save(os.path.join(os.environ["PREVIEW_DIR"], name + ".png"))
    w, h = img.size
    px = img.load()
    rgb, alpha = bytearray(), bytearray()
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            rgb += bytes((v & 0xFF, v >> 8))
            alpha.append(a)
    if fmt == "A8":
        data, stride, cf = alpha, w, "LV_COLOR_FORMAT_A8"
    elif fmt == "RGB565":
        data, stride, cf = rgb, w * 2, "LV_COLOR_FORMAT_RGB565"
    else:
        data, stride, cf = rgb + alpha, w * 2, "LV_COLOR_FORMAT_RGB565A8"
    lines = []
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join("0x%02x" % b for b in data[i:i + 24]) + ",")
    with open(os.path.join(OUT, "img_%s.c" % name), "w") as f:
        f.write("/* generated by tools/make_assets.py */\n#include \"lvgl.h\"\n\n")
        f.write("static const LV_ATTRIBUTE_LARGE_CONST uint8_t %s_map[] __attribute__((aligned(4))) = {\n%s\n};\n\n" % (name, "\n".join(lines)))
        f.write("const lv_image_dsc_t img_%s = {\n"
                "  .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = %s, .w = %d, .h = %d, .stride = %d},\n"
                "  .data_size = sizeof(%s_map),\n  .data = %s_map,\n};\n" % (name, cf, w, h, stride, name, name))
    print("img_%-14s %4dx%-4d %-8s %7d bytes" % (name, w, h, fmt, len(data)))
    return name


def photo(file, w):
    im = Image.open(os.path.join(DESIGN, "assets", file)).convert("RGBA")
    return im.resize((w, round(im.height * w / im.width)), Image.LANCZOS)


def main():
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):            # drop assets that are no longer generated
        if f.startswith("img_") and f.endswith(".c"):
            os.remove(os.path.join(OUT, f))
    names = []
    with tempfile.TemporaryDirectory() as tmp:
        # characters, viewBox 0 0 130 110 facing right
        for ch in ("turtle", "hare", "cheetah"):
            body = svg_group(ch)
            s = 0.9   # on the dial: keeps alpha (crosses the track); the mirrored copy for reverse is built at runtime
            w, h = round(130 * s), round(110 * s)
            img = render('<g transform="scale(%g)">%s</g>' % (s, body), w, h, tmp, ch + "s")
            names.append(to_c(img, "%s_s" % ch))
            # level card: design scale 1.7 -> 2.125 on the panel, opaque on the card colour
            s = 1.7 * K
            w, h = round(130 * s), round(110 * s)
            img = render('<g transform="scale(%g)">%s</g>' % (s, body), w, h, tmp, ch + "c")
            names.append(to_c(flat(img, CARD), "%s_lc" % ch, "RGB565"))
            # Kids theme: the same sprite on the screen colour
            names.append(to_c(flat(img, BG), "%s_lk" % ch, "RGB565"))
            # top-bar level indicator: the same character 0.4 design units wide, opaque on the screen colour
            s = 0.4 * K
            w, h = round(130 * s), round(110 * s)
            img = render('<g transform="scale(%g)">%s</g>' % (s, body), w, h, tmp, ch + "t")
            names.append(to_c(flat(img, BG), "%s_t" % ch, "RGB565"))
            s = 1.7 * K   # restore the card/Kids scale for the next character's sprites

        # alert icons (90x90 design -> 112 px) sit on the flat alert background
        for key, body in re.findall(r"(lowbat|overheat|can):'<svg[^>]*>(.*?)</svg>'", html_src):
            s = 112 / 90
            img = render('<g transform="scale(%g)">%s</g>' % (s, body), 112, 112, tmp, key)
            names.append(to_c(flat(img, BG), "ic_" + key, "RGB565"))

        # telltales (36x36 design units) and the two turn arrows: white shapes, alpha only (A8), recoloured in code
        for key in ("tlLights", "tlTemp", "tlCheck", "tlRemote"):
            m = re.search(r'<g id="%s"[^>]*>(.*?)</g>\n\s*(?:<g id|</svg>)' % key, html_src, re.S)
            if not m:
                raise SystemExit("telltale %s not found in design" % key)
            inner = re.sub(r"<title>.*?</title>", "", m.group(1), flags=re.S)
            inner = re.sub(r'fill="#[0-9a-fA-F]{6}"', 'fill="#fff"', inner)
            body = ('<g transform="scale(%g)" fill="none" stroke="#fff" stroke-width="2.8" stroke-linecap="round" '
                    'stroke-linejoin="round">%s</g>' % (K, inner))
            names.append(to_c(render(body, round(36 * K), round(36 * K), tmp, key), key.lower().replace("tl", "tl_"), "A8"))
        for key, d, x0 in (("turn_l", "M 312 32 L 329 17 L 329 25 L 352 25 L 352 39 L 329 39 L 329 47 Z", 312),
                           ("turn_r", "M 488 32 L 471 17 L 471 25 L 448 25 L 448 39 L 471 39 L 471 47 Z", 448)):
            body = '<g transform="scale(%g) translate(%d -17)"><path d="%s" fill="#fff"/></g>' % (K, -x0, d)
            names.append(to_c(render(body, round(40 * K), round(30 * K), tmp, key), key, "A8"))

        # light sweep band for the crest: always white, so only its alpha is stored (A8, 1 byte per pixel)
        # and it is drawn with image_recolor = white
        band = ('<defs><linearGradient id="b"><stop offset="0" stop-color="#fff" stop-opacity="0"/><stop offset=".5" stop-color="#fff" stop-opacity=".7"/>'
                '<stop offset="1" stop-color="#fff" stop-opacity="0"/></linearGradient></defs>'
                '<rect x="0" y="-40" width="90" height="340" fill="url(#b)" transform="rotate(15 45 130)"/>')
        names.append(to_c(render(band, 90, 260, tmp, "band"), "band", "A8"))

    # photos: one opaque car for the car page and the charging screen, opaque crest for the splash
    names.append(to_c(flat(photo("car-34.png", 400), BG), "car", "RGB565"))
    crest = photo("porsche-crest.png", 195)
    names.append(to_c(flat(crest, BG), "crest", "RGB565"))
    names.append(to_c(crest, "crest_mask", "A8"))

    with open(os.path.join(OUT, "assets.h"), "w") as f:
        f.write("#pragma once\n/* generated by tools/make_assets.py */\n#include \"lvgl.h\"\n\n")
        for n in names:
            f.write("LV_IMAGE_DECLARE(img_%s);\n" % n)
        f.write("\n")
        for fnt in ("r16", "r18", "r20", "r22", "r25", "s28", "s32", "s40", "s50", "s70", "s80", "s90", "s138", "s212", "s238"):
            f.write("LV_FONT_DECLARE(font_%s);\n" % fnt)


if __name__ == "__main__":
    main()
